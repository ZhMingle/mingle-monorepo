import Foundation

@main struct Tests {
    static func main() throws {
        let now = Date()
        let controls = UsageClock()
        assert(controls.actionTitle(idle: 300, locked: false, now: now) == "Resume")
        controls.toggle(idle: 300, now: now)
        controls.step(elapsed: 1, idle: 301, locked: false, now: now.addingTimeInterval(1))
        assert(controls.state.cycle == 1 && !controls.paused, "Resume from auto-idle must start counting")
        assert(controls.actionTitle(idle: 301, locked: false, now: now.addingTimeInterval(1)) == "Pause")
        controls.toggle(idle: 0, now: now); assert(controls.paused)
        assert(controls.actionTitle(idle: 0, locked: false, now: now) == "Resume")
        controls.toggle(idle: 0, now: now); assert(!controls.paused)
        assert(controls.actionTitle(idle: 0, locked: true, now: now) == "Resume")
        controls.toggle(idle: 0, now: now, resumeRequested: true); assert(!controls.paused, "Clicking Resume after mouse input resets idle must still resume")
        controls.rest(now); controls.toggle(idle: 0, now: now); assert(!controls.paused)
        assert(controls.actionTitle(idle: 0, locked: false, now: now) == "On a break")
        let clock = UsageClock()
        clock.step(elapsed: 1, idle: 0, locked: false, now: now)
        assert(clock.state.total == 1)
        clock.step(elapsed: 1, idle: 300, locked: false, now: now)
        clock.step(elapsed: 1, idle: 0, locked: true, now: now)
        clock.step(elapsed: 100, idle: 0, locked: false, now: now)
        assert(clock.state.total == 1, "Idle, lock and sleep must not count")
        clock.state.cycle = 1800; assert(clock.due)
        clock.snooze = 300; assert(!clock.due)
        clock.step(elapsed: 1, idle: 0, locked: false, now: now)
        assert(clock.snooze == 299)
        clock.rest(now)
        clock.step(elapsed: 1000, idle: 1000, locked: true, now: now.addingTimeInterval(301))
        assert(clock.state.breaks == 1 && clock.state.awaitingStart)
        clock.step(elapsed: 1, idle: 0, locked: false, now: now.addingTimeInterval(302))
        assert(clock.state.cycle == 0 && clock.state.breaks == 1)
        clock.confirm(now.addingTimeInterval(303))
        clock.step(elapsed: 1, idle: 900, locked: false, now: now.addingTimeInterval(304))
        assert(clock.state.cycle == 1, "New session gets fresh idle window")
        clock.rest(now); clock.prepare(); clock.confirm(now)
        clock.step(elapsed: 1, idle: 0, locked: false, now: now.addingTimeInterval(400))
        assert(clock.restEnd == nil && clock.state.breaks == 1, "Skipped deadline must be canceled")
        clock.prepare()
        let saved = try JSONDecoder().decode(SavedState.self, from: JSONEncoder().encode(clock.state))
        assert(saved.awaitingStart)
        clock.step(elapsed: 1, idle: 0, locked: false, now: now.addingTimeInterval(86400))
        assert(clock.state.total == 0 && clock.state.breaks == 0 && clock.state.awaitingStart)
        let reading = try UsageReading.parse(["rateLimitsByLimitId": ["codex": ["primary": ["usedPercent": 20, "windowDurationMins": 300], "secondary": ["usedPercent": 35, "windowDurationMins": 10080]]], "rateLimits": ["primary": ["usedPercent": 99]]])
        assert(reading.text.contains("80% left") && reading.text.contains("5h"))
        assert(reading.compactText == "5h: 80% left\nWeekly: 65% left", "Floating timer must retain both allowance windows")
        assert(reading.text.contains("Weekly: 65% left"))
        let missing = try UsageReading.parse(["rateLimits": ["primary": ["usedPercent": NSNull()]]])
        assert(missing.text.contains("Unavailable"))
        assert(missing.compactText.contains("Weekly: Unavailable"))
        print("PASS: active/idle/lock/sleep timing, snooze, breaks, confirmation, skip, persistence, midnight, usage parsing")
        if CommandLine.arguments.contains("--quota-test") {
            let client = UsageClient(); defer { client.close() }
            _ = try client.read(path: "")
            let result = try client.read(path: "")
            print("PASS: two reads through persistent Codex connection\n" + result.text)
        }
    }
}
